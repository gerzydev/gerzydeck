// UI language: English by default, Czech optional. Strings are written in English and looked up here.
// The language lives in the config (shared with the core); localStorage mirrors it so modules can
// translate while they load — a language change reloads the editor.
const KEY = 'gd-lang';
export const lang = (() => { try { return localStorage.getItem(KEY) === 'cs' ? 'cs' : 'en'; } catch { return 'en'; } })();

export function setLang(value) {
  try { localStorage.setItem(KEY, value === 'cs' ? 'cs' : 'en'); } catch { /* private mode: stays English */ }
}

/** t('Key {0}', 3) → translated text with {n} placeholders filled. */
export function t(en, ...args) {
  const s = lang === 'cs' ? (CS[en] ?? en) : en;
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (args[i] ?? m)) : s;
}

/** Count with the right word form: plural(n, 'icon', 'icons') / Czech 1, 2–4, 5+. */
export function plural(n, one, many, csOne, csFew, csMany) {
  if (lang !== 'cs') return `${n} ${n === 1 ? one : many}`;
  return `${n} ${n === 1 ? csOne : n >= 2 && n <= 4 ? csFew : csMany}`;
}

